  await resolved.scrollIntoViewIfNeeded(); await screenshot('03-resolved-expanded');
  await page.getByTestId('layer-button').nth(1).click();
  await expect(inline('sample-single').getByTestId('thread-comment')).toHaveCount(1);
  await inline('sample-single').scrollIntoViewIfNeeded(); await screenshot('04-single-comment');
