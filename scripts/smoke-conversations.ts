  await expect(open.getByRole('alert')).toContainText('draft has been kept'); await expect(open.getByRole('textbox')).toHaveValue('reject');
  await open.getByRole('textbox').fill('I’ll add that regression test.'); await open.getByRole('textbox').press('Control+Enter');
